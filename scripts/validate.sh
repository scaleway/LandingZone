#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Scaleway Landing Zone Toolkit - Repo-wide quality gate (run from repo root):
#
#   1. terraform fmt -check      (repo-wide, recursive)
#   2. terraform validate        (every initialized dir under scw-lz/ + samples/)
#   3. tflint / 4. tfsec         (optional - skipped if not installed)
#   5. repo hygiene: no tracked *.tfvars (secrets stay out of git), .creds/
#      never tracked, required files per stage, Stage-3 ASCII policy, common
#      tags policy (managed-by/env/stage on every resource).
#
# Exit 0 when everything passes, 1+ when something needs fixing.
# ---------------------------------------------------------------------------
set -u

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT" || exit 1

FAILS=0
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

ok()   { printf '%-5s %s\n' "[OK]"   "$1"; }
warn() { printf '%-5s %s\n' "[WARN]" "$1"; }
bad()  { printf '%-5s %s\n' "[FAIL]" "$1"; FAILS=$((FAILS+1)); }
hdr()  { printf '\n== %s ==\n' "$1"; }

command -v terraform >/dev/null 2>&1 || { echo "[FAIL] terraform not found on PATH"; exit 1; }

# ---------------------------------------------------------------------------
# 1. terraform fmt (repo-wide)
# ---------------------------------------------------------------------------
hdr "1. terraform fmt -check (repo-wide)"
if terraform fmt -check -recursive scw-lz/ modules/ samples/ >"$TMP/fmt.out" 2>&1; then
  ok "all files formatted"
else
  # Bootstrap-generated per-env tfvars are re-rendered on every bootstrap, so
  # they're exempt; any SOURCE file with fmt differences still fails.
  if grep -vE '^scw-lz/(backend|backup|providers|remote_state)\.tfvars$|^scw-lz/envs/[^/]+/.*\.tfvars$' "$TMP/fmt.out" | grep -q '[^[:space:]]'; then
    bad "formatting differences - run: terraform fmt -recursive scw-lz/"
    sed 's/^/    /' "$TMP/fmt.out" | tail -15
  else
    warn "generated per-env tfvars need fmt (regenerated by bootstrap) - acceptable"
  fi
fi

# ---------------------------------------------------------------------------
# 2. terraform validate (every initialized dir under scw-lz/)
# ---------------------------------------------------------------------------
DIRS="$(find scw-lz samples -maxdepth 3 -name .terraform -type d -not -path '*/.terraform/*' 2>/dev/null \
        | sed 's#/\.terraform$##' | sort)"
# Fallback when nothing is initialized yet: every dir that actually has .tf
# files (placeholder samples/ dirs with only .gitkeep are skipped).
[ -n "$DIRS" ] || DIRS="$( { ls -d scw-lz/stages/*/ scw-lz/bootstrap/ samples/*/ 2>/dev/null; } \
        | while read -r d; do [ -n "$(ls "$d"/*.tf 2>/dev/null | head -1)" ] && printf '%s\n' "$d"; done | sort -u)"

hdr "2. terraform validate"
for d in $DIRS; do
  if (cd "$d" && terraform validate -no-color >"$TMP/val.out" 2>&1); then
    ok "validate $d"
  else
    bad "validate $d"
    sed 's/^/    /' "$TMP/val.out" | tail -8
  fi
done

# ---------------------------------------------------------------------------
# 3. tflint (optional)
# ---------------------------------------------------------------------------
hdr "3. tflint (optional)"
if command -v tflint >/dev/null 2>&1; then
  if tflint --recursive --chdir scw-lz/ >"$TMP/tflint.out" 2>&1; then
    ok "tflint clean"
  else
    bad "tflint issues"
    sed 's/^/    /' "$TMP/tflint.out" | tail -20
  fi
else
  warn "tflint not installed - skipped (brew install tflint)"
fi

# ---------------------------------------------------------------------------
# 4. tfsec (optional)
# ---------------------------------------------------------------------------
hdr "4. tfsec (optional)"
if command -v tfsec >/dev/null 2>&1; then
  if tfsec scw-lz/ --no-color >"$TMP/tfsec.out" 2>&1; then
    ok "tfsec clean"
  else
    bad "tfsec findings"
    sed 's/^/    /' "$TMP/tfsec.out" | tail -20
  fi
else
  warn "tfsec not installed - skipped (brew install tfsec)"
fi

# ---------------------------------------------------------------------------
# 5. repo hygiene
# ---------------------------------------------------------------------------
hdr "5. repo hygiene"

# 5a. no tracked tfvars with secrets
# The committed envs/{dev,prod}/ tfvars are sanitized PUBLIC templates and
# ARE tracked; live *-demo.tfvars / bootstrap-generated ones must never be.
TRACKED="$(git ls-files -- '*.tfvars' '*.tfvars.json' 2>/dev/null)"
ALLOWED_TFVARS_TEMPLATES="
scw-lz/envs/dev/0-org-setup-dev.tfvars
scw-lz/envs/dev/1-security-dev.tfvars
scw-lz/envs/dev/2-networking-dev.tfvars
scw-lz/envs/dev/3-security-appliances-dev.tfvars
scw-lz/envs/dev/4-project-factory-dev.tfvars
scw-lz/envs/dev/6-interconnection-dev.tfvars
scw-lz/envs/prod/0-org-setup-prod.tfvars
scw-lz/envs/prod/1-security-prod.tfvars
scw-lz/envs/prod/2-networking-prod.tfvars
scw-lz/envs/prod/3-security-appliances-prod.tfvars
scw-lz/envs/prod/4-project-factory-prod.tfvars
scw-lz/envs/prod/6-interconnection-prod.tfvars
"
if [ -n "$TRACKED" ]; then
  bad_tf=""
  while IFS= read -r f; do
    [ -n "$f" ] || continue
    if ! grep -qxF "$f" <<<"$ALLOWED_TFVARS_TEMPLATES"; then
      bad_tf="$bad_tf $f"
    fi
  done <<<"$TRACKED"
  if [ -n "$bad_tf" ]; then
    bad "tracked tfvars found (secrets must never be committed):"
    printf '%s\n' $bad_tf | sed 's/^/    /'
  else
    # Templates must stay placeholder-only: block real-looking values.
    if TRACKED_ALL="$(git ls-files -- 'scw-lz/envs/*/*.tfvars' 2>/dev/null)" && [ -n "$TRACKED_ALL" ]; then
      if grep -qE '[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}|SCW[0-9A-Z]{16,}' $TRACKED_ALL; then
        bad "canonical tfvars template contains real-looking values (UUID / SCW key):"
        grep -lE '[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}|SCW[0-9A-Z]{16,}' $TRACKED_ALL | sed 's/^/    /'
      else
        ok "no tracked *.tfvars with secrets (canonical templates are placeholder-only)"
      fi
    fi
  fi
else
  ok "no tracked *.tfvars"
fi

# 5a2. .creds/ is gitignored but lives in the repo tree - a broken .gitignore
# or `git add -f` would leak every env secret.
CREDS_TRACKED="$(git ls-files -- .creds 2>/dev/null)"
if [ -n "$CREDS_TRACKED" ]; then
  bad "tracked .creds/* files (credentials must never be committed):"
  printf '%s\n' "$CREDS_TRACKED" | sed 's/^/    /'
else
  ok "no tracked .creds/* (folder is gitignored; contents stay local)"
fi

# 5b. required files per stage
for d in scw-lz/stages/*/; do
  [ -d "$d" ] || continue
  base="$(basename "$d")"
  MISSING=""
  for f in main.tf variables.tf outputs.tf; do
    [ -f "$d/$f" ] || MISSING="$MISSING $f"
  done
  if [ -n "$MISSING" ]; then
    bad "stage $base missing:$MISSING"
  else
    ok "stage $base files ok"
  fi
done

# 5c. Stage-3 ASCII policy (no non-ASCII in code + docs)
# opnsense-config.xml.tftpl is deliberately excluded: it renders into the live
# firewall config, so ASCII-ifying it would force a config re-import/reboot on
# the HA pair. The per-env factory yamls are scanned too (Stage-3's design data).
STAGE3="scw-lz/stages/3-security-appliances"
NONASCII="$(LC_ALL=C grep -rl '[^ -~]' \
    "$STAGE3/main.tf" \
    "$STAGE3/variables.tf" \
    "$STAGE3/outputs.tf" \
    "$STAGE3/README.md" \
    "$STAGE3/PROVIDERS.md" \
    "$STAGE3/providers/opnsense/test-firewalls.sh" \
    "$STAGE3/terraform.tfvars.sample" \
    "$STAGE3/providers/" \
    scw-lz/envs/*/data/security-appliances-*.yaml 2>/dev/null | grep -v  'opnsense-config.xml.tftpl')"
if [ -n "$NONASCII" ]; then
  bad "Stage-3 ASCII policy violated in:"
  printf '%s\n' "$NONASCII" | sed 's/^/    /'
else
  ok "Stage-3 ASCII policy holds"
fi

# 5d. Common tags policy. Composition (the operator's var.common_tags plus the
# toolkit-reserved markers managed-by / env / stage) lives ONCE in
# modules/tags (single source of truth); every toolkit stage consumes it via
# module "common_tags" and feeds it var.common_tags. Bare hardcoded
# `tags = [...]` in resources stays banned. Samples are self-contained
# examples: they keep the markers inline (marker check still applies) and are
# exempt from the module-wiring requirement.
TAG_MODULE_DIR="modules/tags"
STAGE_FILES="scw-lz/bootstrap/main.tf scw-lz/stages/*/main.tf"
SAMPLE_FILES="samples/*/main.tf"
COMMON_TAGS_BAD=""

# 1) Single point: modules/tags carries the reserved markers + both output
#    forms (list for instance-like resources, map for object storage buckets).
#    Markers are key=value: Scaleway rejects `:` in IAM tag values.
if [ ! -f "$TAG_MODULE_DIR/main.tf" ]; then
  COMMON_TAGS_BAD="$COMMON_TAGS_BAD\n  $TAG_MODULE_DIR/: missing (single source of truth for common tags)"
else
  for marker in "managed-by=" 'env=${' 'stage=${'; do
    if ! grep -qF "$marker" "$TAG_MODULE_DIR/main.tf"; then
      COMMON_TAGS_BAD="$COMMON_TAGS_BAD\n  $TAG_MODULE_DIR/main.tf: missing marker \"$marker\""
    fi
  done
  for out in 'output "list"' 'output "map"'; do
    if ! grep -qF "$out" "$TAG_MODULE_DIR/outputs.tf" 2>/dev/null; then
      COMMON_TAGS_BAD="$COMMON_TAGS_BAD\n  $TAG_MODULE_DIR/outputs.tf: missing $out"
    fi
  done
fi

# 2) Every toolkit stage consumes the module and feeds it var.common_tags; the
#    stage must still declare the variable (users plan org tags there).
for f in $STAGE_FILES; do
  [ -f "$f" ] || continue
  if ! grep -q 'module "common_tags"' "$f"; then
    COMMON_TAGS_BAD="$COMMON_TAGS_BAD\n  $f: missing module \"common_tags\" (single source of truth: modules/tags)"
  fi
  if ! grep -q "var.common_tags" "$f"; then
    COMMON_TAGS_BAD="$COMMON_TAGS_BAD\n  $f: module.common_tags must receive user_tags = var.common_tags (org tag policy)"
  fi
  if ! grep -q 'variable "common_tags"' "${f%/main.tf}/variables.tf" 2>/dev/null; then
    COMMON_TAGS_BAD="$COMMON_TAGS_BAD\n  $f: uses var.common_tags but variables.tf does not declare it (add variable \"common_tags\")"
  fi
  # 3) A literal `tags = [...]`/`{...}` with no common reference is a violation.
  while IFS= read -r line; do
    case "$line" in
      *"#"*|*"concat("*|*"merge("*|*"lookup("*|*"try("*|*"coalesce("*|*"common_tags"*) continue ;;
    esac
    case "$line" in
      *"tags"*"="*"["*|*"tags"*"="*"{"*)
        COMMON_TAGS_BAD="$COMMON_TAGS_BAD\n  $f: bare tags literal -> $(printf '%s' "$line" | sed 's/^[[:space:]]*//')" ;;
    esac
  done < <(grep -nE 'tags[[:space:]]*=' "$f")
done

# 4) Samples stay self-contained: markers must still be present inline.
for f in $SAMPLE_FILES; do
  [ -f "$f" ] || continue
  TAGBLOCK="$(python3 - "$f" <<'PYEOF'
import sys
src = open(sys.argv[1], encoding="utf-8").read()
i = src.find("common_tags =")
if i < 0:
    sys.exit(0)
j = src.index("=", i) + 1
depth = 0
end = j
for k in range(j, len(src)):
    c = src[k]
    if c in "[{(":
        depth += 1
    elif c in "]})":
        depth -= 1
        if depth == 0:
            end = k + 1
            break
print(src[i:end])
PYEOF
)"
  if [ -z "$TAGBLOCK" ]; then
    COMMON_TAGS_BAD="$COMMON_TAGS_BAD\n  $f: missing common_tags definition (all resources need managed-by/env/stage)"
    continue
  fi
  for marker in "managed-by=landing-zone-toolkit" 'env=${' 'stage='; do
    case "$TAGBLOCK" in
      *"$marker"*) ;;
      *) COMMON_TAGS_BAD="$COMMON_TAGS_BAD\n  $f: common_tags missing marker \"$marker\"" ;;
    esac
  done
done
if [ -n "$COMMON_TAGS_BAD" ]; then
  bad "common tags policy violated:"
  printf '%b\n' "$COMMON_TAGS_BAD" | sed 's/^/    /'
else
  ok "common tags policy holds (org tags + reserved markers via modules/tags)"
fi

# 5e. Offline regression suite (fw-tool + CLI driver). No cloud,
# no network, no credentials -- see tests/run-tests.sh.
if command -v python3 >/dev/null 2>&1; then
  if bash tests/run-tests.sh >"$TMP/tests.out" 2>&1; then
    ok "offline tests pass (fw-tool, CLI driver)"
  else
    bad "offline tests failed:"
    sed 's/^/    /' "$TMP/tests.out" | tail -12
  fi
else
  bad "python3 not found (required by tests/run-tests.sh)"
fi

# ---------------------------------------------------------------------------
# summary
# ---------------------------------------------------------------------------
hdr "summary"
if [ "$FAILS" -eq 0 ]; then
  ok "all checks green"
else
  bad "$FAILS check(s) failing"
fi
exit "$FAILS"
