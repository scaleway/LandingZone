#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Scaleway Landing Zone Toolkit -- Generate the firewall test battery env file.
#
#   ./scripts/gen_fw_battery_env.sh [ENV]
#
# ENVIRONMENT defaults to $ENV, then "dev". Reads the live stage-3
# `firewall_test_config` output and writes scw-lz/envs/<ENV>/test-firewalls.env
# (consumed by scw-lz/stages/3-security-appliances/providers/opnsense/test-firewalls.sh).
#
# Everything in the env file is DERIVED - no hand-maintained values: live IPs
# + FW base-IDs from stage-3 remote state, the rest from the
# security-appliances factory yaml. Re-run after any rebuild: make fw-test-env
# (the battery auto-runs this when the env file is missing).
# ---------------------------------------------------------------------------
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
source "${SCRIPT_DIR}/lib/stages.sh"

ENV_NAME="${1:-${ENV:-dev}}"
STAGE_DIR="${REPO_ROOT}/scw-lz/stages/3-security-appliances"
ENV_DIR="${REPO_ROOT}/scw-lz/envs/${ENV_NAME}"
OUTFILE="${ENV_DIR}/test-firewalls.env"
back="$(envcfg backend)"   # relative to the stage dir (terraform cwd)

# The battery must run against an env built by this pipeline.
for f in "${ENV_DIR}/backend-${ENV_NAME}.tfvars" \
         "${ENV_DIR}/providers-${ENV_NAME}.tfvars" \
         "${ENV_DIR}/remote_state-${ENV_NAME}.tfvars"; do
  [[ -f "${f}" ]] || { echo "error: missing ${f} -- run make bootstrap first." >&2; exit 1; }
done

cd "${STAGE_DIR}"
if ! terraform init -input=false -reconfigure -backend-config="${back}" >/dev/null 2>&1; then
  echo "error: terraform init failed in stage-3 (need the remote state backend)." >&2
  exit 1
fi

if ! CAP="$(terraform output -json firewall_test_config)"; then
  echo "error: stage-3 output 'firewall_test_config' not found - re-apply stage-3 first (make apply STAGE=3)." >&2
  exit 1
fi

# Values the battery requires (must be present and non-empty).
REQUIRED=(DOOR EGRESS SPOKE1_IP SPOKE2_IP SPOKE1_PRIV SPOKE2_PRIV HUBTEST_PRIV MGMT_CIDRS FW_PASSIVE_UUID FW_ACTIVE_UUID)
# Values the battery would otherwise hardcode as blueprint defaults.
OPTIONAL=(FW_PASSIVE_ZONE FW_ACTIVE_ZONE LAN_VIP EGRESS_VIP EGRESS_PGW EGRESS_PGW_PASSIVE HUB_PGW HUB_PGW_PASSIVE DOOR_PASSIVE EGRESS_PASSIVE)

get() { jq -r --arg k "$1" '.[$k] // empty' <<< "${CAP}"; }

missing=0
{
  printf '%s\n' "# ---------------------------------------------------------------------------"
  printf '%s\n' "# GENERATED by scripts/gen_fw_battery_env.sh (make fw-test-env) - NOT hand-maintained."
  printf '%s\n' "# Source of truth: stage-3 output 'firewall_test_config' (live state) + the"
  printf '%s\n' "# security-appliances factory yaml. Regenerate after any rebuild:  make fw-test-env"
  printf '# Generated: %s\n' "$(date '+%Y-%m-%d %H:%M:%S')"
  printf '%s\n' "# ---------------------------------------------------------------------------"

  for k in "${REQUIRED[@]}"; do
    v="$(get "${k}")"
    if [[ -z "${v}" ]]; then
      echo "[WARN] ${k} empty/null - it will not be written" >&2
      missing=1
      continue
    fi
    printf '%s=%s\n' "${k}" "${v}"
  done
  for k in "${OPTIONAL[@]}"; do
    v="$(get "${k}")"
    [[ -n "${v}" ]] && printf '%s=%s\n' "${k}" "${v}"
  done
} > "${OUTFILE}"

if [[ "${missing}" -eq 1 ]]; then
  echo "[WARN] some values were empty - check stage-3 (are test instances enabled? create_test_instances)." >&2
fi

echo "Generated ${OUTFILE}"
echo "  DOOR=${DOOR:-$(get DOOR)}  EGRESS=$(get EGRESS)  SPOKE1=$(get SPOKE1_IP)  SPOKE2=$(get SPOKE2_IP)"
echo "  FW_PASSIVE=$(get FW_PASSIVE_UUID)  FW_ACTIVE=$(get FW_ACTIVE_UUID)"
