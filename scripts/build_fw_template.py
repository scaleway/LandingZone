#!/usr/bin/env python3

"""Build a reusable sanitized OPNsense config template from a live config.

Usage:
    python3 scripts/build_fw_template.py <source-config.xml> [output-dir]

Example:
    python3 scripts/build_fw_template.py tmp/fw_passive_config_downloaded.xml
    # -> modules/firewall/config/opnsense/templates/vpc-hub-spoke-fw.xml

The script strips secrets (root password, TLS cert/key, authorized keys) and
replaces environment-specific values with placeholders so the template can be
shared and reused for other firewall nodes (e.g., fw-active).
"""
import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

DEFAULT_DST_DIR = Path('modules/firewall/config/opnsense/templates')
DEFAULT_DST = DEFAULT_DST_DIR / 'vpc-hub-spoke-fw.xml'

# environment-specific values -> placeholders
REPLACEMENTS = [
    # hostname / domain
    ('<hostname>OPNsense</hostname>', '<hostname>FW-PASSIVE</hostname>'),
    ('<domain>internal</domain>', '<domain>example.internal</domain>'),
]


def sanitize_xml(xml_text: str) -> str:
    """Remove secrets and environment-specific data."""
    # 1. Remove the autogenerated TLS certificate + private key (per-install)
    xml_text = re.sub(r'(<cert>.*?</cert>)', '<cert/>', xml_text, flags=re.S)
    # 2. Remove root password hash
    xml_text = re.sub(r'(<password>).*?(</password>)', r'\1CHANGE_ME\2', xml_text)
    # 3. Remove authorized keys contents
    xml_text = re.sub(r'(<authorizedkeys>).*?(</authorizedkeys>)', r'\1\2', xml_text)
    # 4. Remove revision metadata (local admin source)
    xml_text = re.sub(r'<revision>.*?</revision>', '<revision/>', xml_text, flags=re.S)
    # 5. Remove update/created metadata blocks inside rules
    xml_text = re.sub(r'<updated>.*?</updated>', '', xml_text, flags=re.S)
    xml_text = re.sub(r'<created>.*?</created>', '', xml_text, flags=re.S)
    return xml_text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('source', type=Path,
                        help='Path to a live OPNsense config.xml')
    parser.add_argument('output', nargs='?', type=Path, default=DEFAULT_DST,
                        help=f'Output template path (default: {DEFAULT_DST})')
    args = parser.parse_args()

    if not args.source.is_file():
        print(f'ERROR: source file not found: {args.source}', file=sys.stderr)
        return 1

    raw = args.source.read_text()
    cleaned = sanitize_xml(raw)
    for old, new in REPLACEMENTS:
        cleaned = cleaned.replace(old, new)

    # Validate before writing
    try:
        ET.fromstring(cleaned)
    except ET.ParseError as e:
        print(f'ERROR: sanitized XML is invalid: {e}', file=sys.stderr)
        return 1

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(cleaned)
    print(f'Wrote {args.output} ({len(cleaned)} bytes)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
